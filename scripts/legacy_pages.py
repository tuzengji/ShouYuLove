"""Bring the pages still on the old Astra runtime in line with the new home page and portfolio.

`/projects/<id>/` and `/the-studio/` are generated by build_content.py from archived records that
are not always at hand. Rather than rebuilding them, `refresh()` (called by `build_home.py --site`)
edits the published files in place:

- each work's picture becomes its brightened, tonal drawing on a paper scrap, the same as on the
  portfolio (`<id>-square.<hash>.png`);
- the site icon, touch icon, install icons and web manifest are redrawn from the brand mark in the
  same style (`favicon.<hash>.png` and so on), and the new pages link to them too;
- category names and one-line descriptions follow the bound Markdown again;
- the page data script `local-bridge.<hash>.js` is rewritten to match.

Every new file is named by its content, because versioned assets are cached for a year. Old files
stay on the whitelist for pages that are already open. Running it again changes nothing.
"""

import functools
import hashlib
import io
import json
import os
import re
import sys
from pathlib import Path

if sys.platform == "darwin":  # cairosvg finds Homebrew's cairo only when told where to look
    os.environ.setdefault("DYLD_FALLBACK_LIBRARY_PATH", "/opt/homebrew/lib:/usr/local/lib")
import cairosvg  # noqa: E402
from PIL import Image

import icon_style

ROOT = Path(__file__).resolve().parents[1]
SHARED = "sites/immersive-g-com-955afd14/shared"
BRAND_MARK = ROOT / "project-logos/20261012-主站-把爱递给你/shouyulove.svg"
PAPER = "#fffdfa"
SQUARE = 640
CDN = r"(?:https://assets\.shouyulove\.cn/v/[^/\"\\]+)?"
SQUARE_URL = re.compile(CDN + r"/" + re.escape(SHARED) + r"/shouyulove/([a-z0-9-]+?)-square\.[A-Za-z0-9._-]+?\.png")
BRAND_URL = re.compile(CDN + r"/" + re.escape(SHARED) + r"/shouyulove/(favicon|apple-touch-icon|home-icon-192|home-icon-512|works-manifest)\.[A-Za-z0-9._-]+?\.(?:png|json)")
BRIDGE_URL = re.compile(CDN + r"/" + re.escape(SHARED) + r"/local-bridge\.[A-Za-z0-9._-]+?\.js")


def named(stem, data, suffix):
    return f"{SHARED}/{stem}.{hashlib.sha256(data).hexdigest()[:10]}.{suffix}"


def png(picture):
    data = io.BytesIO()
    picture.save(data, "PNG", optimize=True)
    return data.getvalue()


def scrap(shape, turn, colour, size):
    """The paper scrap behind a drawing, as CSS draws it: `border-radius: shape` on a 92% square, turned by `turn`."""
    horizontal, vertical = (part.split() for part in shape.split("/"))
    inset, side = size * .04, size * .92
    rx = [float(value.rstrip("%")) / 100 * side for value in horizontal]
    ry = [float(value.rstrip("%")) / 100 * side for value in vertical]
    left, top, right, bottom = inset, inset, inset + side, inset + side
    path = (f"M{left + rx[0]} {top} H{right - rx[1]} A{rx[1]} {ry[1]} 0 0 1 {right} {top + ry[1]} "
            f"V{bottom - ry[2]} A{rx[2]} {ry[2]} 0 0 1 {right - rx[2]} {bottom} "
            f"H{left + rx[3]} A{rx[3]} {ry[3]} 0 0 1 {left} {bottom - ry[3]} "
            f"V{top + ry[0]} A{rx[0]} {ry[0]} 0 0 1 {left + rx[0]} {top} Z")
    drawing = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 {size} {size}">'
               f'<path d="{path}" fill="{colour}" transform="rotate({turn} {size / 2} {size / 2})"/></svg>')
    return Image.open(io.BytesIO(cairosvg.svg2png(bytestring=drawing.encode()))).convert("RGBA")


def drawing_on(picture, mark, box):
    """Trim the drawing to what is visible and centre it in `box` (left, top, side)."""
    bounds = mark.getchannel("A").point(lambda value: 255 if value >= 128 else 0).getbbox()
    mark = mark.crop(bounds)
    left, top, side = box
    scale = side / max(mark.size)
    mark = mark.resize((round(mark.width * scale), round(mark.height * scale)), Image.Resampling.LANCZOS)
    picture.alpha_composite(mark, (round(left + (side - mark.width) / 2), round(top + (side - mark.height) / 2)))
    return picture


def square(master, paper, shape, turn):
    picture = Image.new("RGBA", (SQUARE, SQUARE), PAPER)
    picture.alpha_composite(scrap(shape, turn, paper, SQUARE))
    return png(drawing_on(picture, Image.open(master).convert("RGBA"), (SQUARE * .17, SQUARE * .17, SQUARE * .66)).convert("RGB"))


@functools.lru_cache(maxsize=None)
def brand():
    """The site's icons, redrawn from the brand mark: {kind: (address, bytes)}."""
    drawing = icon_style.tonal(BRAND_MARK.read_text(encoding="utf-8"))
    mark = Image.open(io.BytesIO(cairosvg.svg2png(bytestring=drawing.encode(), output_width=1024, output_height=1024))).convert("RGBA")
    files = {"favicon": png(mark.resize((64, 64), Image.Resampling.LANCZOS))}
    # Launchers want an opaque tile with some margin around the drawing.
    tile = drawing_on(Image.new("RGBA", (1024, 1024), PAPER), mark, (1024 * .12, 1024 * .12, 1024 * .76)).convert("RGB")
    files["apple-touch-icon"] = png(tile.resize((180, 180), Image.Resampling.LANCZOS))
    for size in (192, 512):
        files[f"home-icon-{size}"] = png(tile.resize((size, size), Image.Resampling.LANCZOS))
    addresses = {kind: (named("shouyulove/" + kind, data, "png"), data) for kind, data in files.items()}
    manifest = dict(id="/projects/", name="以手予爱 ShouYuLove", short_name="以手予爱", lang="zh-CN",
                    start_url="/portfolio/", scope="/portfolio/", display="standalone",
                    icons=[dict(src="/" + addresses[f"home-icon-{size}"][0], sizes=f"{size}x{size}", type="image/png") for size in (192, 512)],
                    theme_color=PAPER, background_color=PAPER)
    data = (json.dumps(manifest, ensure_ascii=False) + "\n").encode()
    addresses["works-manifest"] = (named("shouyulove/works-manifest", data, "json"), data)
    return addresses


def write(name, data):
    path = ROOT / name
    if not path.is_file() or path.read_bytes() != data:
        path.write_bytes(data)
    return name


def refresh(content, masters, papers, scraps, routes, files):
    """Rewrite the old pages. `masters`, `papers` and `scraps` map a work to its drawing, paper colour and scrap;
    `routes` and `files` come from the runtime manifest. Returns every file written or edited."""
    written = [write(address, data) for address, data in brand().values()]
    squares = {}
    for project in content["projects"]:
        shape, turn = scraps[project["id"]]
        data = square(masters[project["id"]], papers[project["id"]], shape, turn)
        squares[project["id"]] = write(named(f"shouyulove/{project['id']}-square", data, "png"), data)
    written += squares.values()

    pages = [name for name in routes.values() if name not in ("index.html", "portfolio/index.html")]
    pages += sorted(name for name in files if name.endswith("_payload.json"))
    documents = {name: (ROOT / name).read_text(encoding="utf-8") for name in pages}
    bridges = {match.group(0) for document in documents.values() for match in BRIDGE_URL.finditer(document)}
    assert len(bridges) == 1, f"The old pages should share one page data script: {bridges}"
    bridge_name = re.sub(r"^.*?/(sites/)", r"\1", bridges.pop())
    bridge = json.loads((ROOT / bridge_name).read_text(encoding="utf-8").split("=", 1)[1].rstrip(";\n"))

    # What the old pages say about each work, and what the source says now.
    changes = {}
    for project in content["projects"]:
        page = bridge["projects/" + project["id"]]
        changes[page["projectType"]] = project["category"]
        said = next(block["text2"] for block in page["blocks"] if block.get("type") == "text").split("\n", 1)[0]
        changes[said] = project["description"]
    changes = {old: new for old, new in changes.items() if old != new}

    def rewrite(text):
        text = SQUARE_URL.sub(lambda match: "/" + squares[match.group(1)] if match.group(1) in squares else match.group(0), text)
        text = BRAND_URL.sub(lambda match: "/" + brand()[match.group(1)][0], text)
        for old, new in sorted(changes.items(), key=lambda item: -len(item[0])):
            text = text.replace(old, new)
        return text

    script = rewrite(json.dumps(bridge, ensure_ascii=False, separators=(",", ":")))
    data = ("window.__IG_LOCAL_PAGES__=" + script + ";\n").encode()
    bridge_address = write(named("local-bridge", data, "js"), data)
    written.append(bridge_address)
    for name, document in documents.items():
        updated = BRIDGE_URL.sub("/" + bridge_address, rewrite(document))
        if updated != document:
            (ROOT / name).write_text(updated, encoding="utf-8")
            written.append(name)
    return written
